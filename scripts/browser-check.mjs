import { chromium, expect } from '/Users/gracebilliris/Projects/brick-by-brick/node_modules/@playwright/test/index.mjs'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'

const baseURL = process.argv[2] || 'http://127.0.0.1:5190/'
const label = baseURL.startsWith('http://127.') ? 'local' : 'production'
await mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('response', response => {
  if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`)
})
page.on('request', request => {
  if (new URL(request.url()).origin !== new URL(baseURL).origin) errors.push(`Unexpected external request: ${request.url()}`)
})
try {
  const response = await page.goto(baseURL)
  assert.equal(response.status(), 200)
  await page.getByRole('heading', { name: /a little time/i }).waitFor()
  await expect(page.locator('.discovery-card')).toHaveCount(6)
  await page.getByRole('button', { name: 'Show 6 more places', exact: true }).click()
  await expect(page.locator('.discovery-card')).toHaveCount(12)
  while (await page.getByRole('button', { name: /Show .* more places/ }).count()) {
    await page.getByRole('button', { name: /Show .* more places/ }).click()
  }
  await expect(page.locator('.discovery-card')).toHaveCount(21)
  const photoPaths = new Set()
  for (const card of await page.locator('.discovery-card').all()) {
    const image = card.locator('img')
    await image.scrollIntoViewIfNeeded()
    await expect.poll(() => image.evaluate(node => node.complete && node.naturalWidth > 0)).toBe(true)
    assert.ok((await image.getAttribute('alt')).length > 20)
    for (const source of (await image.getAttribute('srcset')).split(',')) photoPaths.add(source.trim().split(' ')[0])
    await expect(card.locator('.photo-credit a')).toHaveCount(2)
  }
  for (const path of photoPaths) {
    const photo = await context.request.get(new URL(path, baseURL).href)
    assert.equal(photo.status(), 200, path)
    assert.match(photo.headers()['content-type'], /image\/webp/, path)
  }
  await page.getByRole('link', { name: 'Photo credits', exact: true }).click()
  await expect(page.locator('.photo-credits')).toHaveAttribute('open', '')
  await expect(page.locator('.photo-credits li')).toHaveCount(21)
  await expect(page.locator('.photo-credits')).toContainText('Resized', { ignoreCase: true })
  await page.locator('.photo-credits summary').click()
  const fallbackPage = await context.newPage()
  await fallbackPage.route('**/photos/quay-promenade*.webp', route => route.abort())
  await fallbackPage.goto(baseURL)
  await expect(fallbackPage.getByRole('img', { name: /Photo unavailable:.*Circular Quay/ }).first()).toBeVisible()
  await fallbackPage.getByRole('button', { name: 'Generate itinerary' }).click()
  assert.ok(await fallbackPage.getByTestId('itinerary-stop').count() > 0)
  await fallbackPage.close()
  await page.locator('.discovery-filters').getByRole('button', { name: 'Nature', exact: false }).click()
  assert.ok(await page.locator('.discovery-card').count() <= 6)
  await page.getByRole('button', { name: /All little discoveries/ }).click()
  await expect(page.locator('.discovery-card')).toHaveCount(6)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  const firstInput = await page.locator('#available-time').boundingBox()
  assert.ok(firstInput.y + firstInput.height < 844, 'Preferences should be reachable in the first mobile screen')
  await page.locator('#starting-area').selectOption('Central')
  await page.locator('#available-time').fill('240')
  await page.locator('#budget').fill('0')
  await page.getByRole('button', { name: 'Generate itinerary' }).click()
  await expect(page.locator('.itinerary-heading h3')).toBeFocused()
  await expect(page.locator('.itinerary-heading h3')).toBeInViewport()
  await page.getByRole('link', { name: /Change time, budget or interests/ }).click()
  await expect(page.locator('#available-time')).toBeInViewport()
  await page.setViewportSize({ width: 1440, height: 1000 })
  const stops = page.getByTestId('itinerary-stop')
  assert.ok(await stops.count() >= 2)
  const first = await stops.nth(0).locator('h4').innerText()
  const second = await stops.nth(1).locator('h4').innerText()
  await stops.nth(1).getByRole('button', { name: `Move ${second} up`, exact: true }).click()
  assert.equal(await stops.nth(0).locator('h4').innerText(), second)
  assert.equal(await stops.nth(1).locator('h4').innerText(), first)

  const duration = stops.first().getByRole('spinbutton')
  const oldDuration = await duration.inputValue()
  await duration.fill('360')
  await page.getByRole('alert').filter({ hasText: /Time limit exceeded/ }).waitFor()
  await duration.fill(oldDuration)
  const removed = await stops.last().locator('h4').innerText()
  const count = await stops.count()
  await stops.last().getByRole('button', { name: `Remove ${removed}`, exact: true }).click()
  assert.equal(await stops.count(), count - 1)
  while (!await page.getByRole('button', { name: `Add ${removed} to itinerary`, exact: true }).count()) {
    await page.getByRole('button', { name: /Show .* more places/ }).click()
  }
  await page.getByRole('button', { name: `Add ${removed} to itinerary`, exact: true }).click()
  assert.equal(await stops.count(), count)
  await page.getByRole('button', { name: 'Save plan', exact: false }).click()
  await page.getByRole('status').filter({ hasText: 'Plan saved on this browser' }).waitFor()
  const storage = await page.evaluate(() => JSON.parse(localStorage.getItem('sydney-afternoon:favorites:v1')))
  assert.equal(storage[0].preferences.area, 'Circular Quay')
  await page.reload()
  await page.getByRole('button', { name: /Load A Sydney afternoon/ }).click()
  assert.equal(await stops.nth(0).locator('h4').innerText(), second)
  await page.locator('.route-origin').filter({ hasText: 'Circular Quay' }).waitFor()
  await page.getByRole('button', { name: /Share link/ }).click()
  const sharedURL = await page.locator('#share-link').inputValue()
  assert.ok(sharedURL.includes('#'))
  const sharePage = await context.newPage()
  await sharePage.goto(sharedURL)
  assert.equal(await sharePage.getByTestId('itinerary-stop').first().locator('h4').innerText(), second)
  await sharePage.close()

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download plan', exact: true }).click()
  const download = await downloadPromise
  await download.saveAs(`artifacts/${label}-plan.json`)
  const exported = JSON.parse(await readFile(`artifacts/${label}-plan.json`, 'utf8'))
  assert.equal(exported.stops.length, count)
  await page.evaluate(() => { window.print = () => { document.body.dataset.printed = 'yes' } })
  await page.getByRole('button', { name: 'Print', exact: true }).click()
  assert.equal(await page.locator('body').getAttribute('data-printed'), 'yes')
  const directions = page.getByRole('link', { name: /Open walking directions/ })
  assert.match(await directions.getAttribute('href'), /^https:\/\/www.google.com\/maps\/dir/)
  await page.screenshot({ path: `artifacts/${label}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await page.screenshot({ path: `artifacts/${label}-mobile.png`, fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('navigation', { name: 'Planner sections' })).toBeHidden()
  await expect(page.locator('.stop-photo').first()).toBeHidden()
  await expect(page.locator('.photo-credits')).toBeHidden()
  await page.pdf({ path: `artifacts/${label}-print.pdf`, format: 'A4' })
  await page.emulateMedia({ media: 'screen' })

  await page.locator('#available-time').fill('15')
  await page.getByRole('button', { name: 'Generate itinerary' }).click()
  assert.equal(await stops.count(), 0)
  await page.getByRole('heading', { name: 'A little room for possibility.' }).waitFor()
  assert.deepEqual(errors, [])
  console.log(`${label}: all21 destination photos decode, responsive image assets return200, credits/licenses, image failure fallback and no external image requests; mobile first-screen preferences, result focus, guide filters; generate, reorder, save/reload/privacy, share, download, text-only print, maps and empty plan: PASS`)
} finally {
  await browser.close()
}
