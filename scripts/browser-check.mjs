import { chromium } from '/Users/gracebilliris/Projects/brick-by-brick/node_modules/@playwright/test/index.mjs'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'

const baseURL = process.argv[2] || 'http://127.0.0.1:5190/'
const label = baseURL.startsWith('http://127.') ? 'local' : 'production'
await mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  const response = await page.goto(baseURL)
  assert.equal(response.status(), 200)
  await page.getByRole('heading', { name: /a little time/i }).waitFor()
  await page.locator('#starting-area').selectOption('Central')
  await page.locator('#available-time').fill('240')
  await page.locator('#budget').fill('0')
  await page.getByRole('button', { name: 'Generate itinerary' }).click()
  const stops = page.getByTestId('itinerary-stop')
  assert.ok(await stops.count() >= 2)
  const first = await stops.nth(0).locator('h4').innerText()
  const second = await stops.nth(1).locator('h4').innerText()
  await stops.nth(1).getByRole('button', { name: `Move ${second} up`, exact: true }).click()
  assert.equal(await stops.nth(0).locator('h4').innerText(), second)
  assert.equal(await stops.nth(1).locator('h4').innerText(), first)

  const duration = stops.first().getByRole('spinbutton')
  const oldDuration = await duration.inputValue()
  await duration.fill('360')
  await page.getByRole('alert').filter({ hasText: /Time limit exceeded/ }).waitFor()
  await duration.fill(oldDuration)
  const removed = await stops.last().locator('h4').innerText()
  const count = await stops.count()
  await stops.last().getByRole('button', { name: `Remove ${removed}`, exact: true }).click()
  assert.equal(await stops.count(), count - 1)
  await page.getByRole('button', { name: `Add ${removed} to itinerary`, exact: true }).click()
  assert.equal(await stops.count(), count)
  await page.getByRole('button', { name: 'Save plan', exact: false }).click()
  await page.getByRole('status').filter({ hasText: 'Plan saved on this browser' }).waitFor()
  const storage = await page.evaluate(() => JSON.parse(localStorage.getItem('sydney-afternoon:favorites:v1')))
  assert.equal(storage[0].preferences.area, 'Circular Quay')
  await page.reload()
  await page.getByRole('button', { name: /Load A Sydney afternoon/ }).click()
  assert.equal(await stops.nth(0).locator('h4').innerText(), second)
  await page.locator('.route-origin').filter({ hasText: 'Circular Quay' }).waitFor()
  await page.getByRole('button', { name: /Share link/ }).click()
  const sharedURL = await page.locator('#share-link').inputValue()
  assert.ok(sharedURL.includes('#'))
  const sharePage = await context.newPage()
  await sharePage.goto(sharedURL)
  assert.equal(await sharePage.getByTestId('itinerary-stop').first().locator('h4').innerText(), second)
  await sharePage.close()

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download plan', exact: true }).click()
  const download = await downloadPromise
  await download.saveAs(`artifacts/${label}-plan.json`)
  const exported = JSON.parse(await readFile(`artifacts/${label}-plan.json`, 'utf8'))
  assert.equal(exported.stops.length, count)
  await page.evaluate(() => { window.print = () => { document.body.dataset.printed = 'yes' } })
  await page.getByRole('button', { name: 'Print', exact: true }).click()
  assert.equal(await page.locator('body').getAttribute('data-printed'), 'yes')
  const directions = page.getByRole('link', { name: /Open walking directions/ })
  assert.match(await directions.getAttribute('href'), /^https:\/\/www.google.com\/maps\/dir/)
  await page.screenshot({ path: `artifacts/${label}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await page.screenshot({ path: `artifacts/${label}-mobile.png`, fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await page.pdf({ path: `artifacts/${label}-print.pdf`, format: 'A4' })
  await page.emulateMedia({ media: 'screen' })

  await page.locator('#available-time').fill('15')
  await page.getByRole('button', { name: 'Generate itinerary' }).click()
  assert.equal(await stops.count(), 0)
  await page.getByRole('heading', { name: 'A little room for possibility.' }).waitFor()
  assert.deepEqual(errors, [])
  console.log(`${label}: generate, free budget, reorder, duration warning, remove/add, save/reload/privacy, share, JSON download, print, maps, mobile, empty plan: PASS`)
} finally {
  await browser.close()
}
